SELECT
    CAST(TRIM(EVENT_ID) AS VARCHAR) AS EVENT_ID,
    CAST(TRIM(USER_ID) AS VARCHAR) AS USER_ID,
    CAST(TRIM(USER_NAME) AS VARCHAR) AS USER_NAME,
    CAST(TRIM(USER_COUNTRY) AS VARCHAR) AS USER_COUNTRY,
    CAST(TRIM(USER_SUBSCRIPTION_TIER) AS VARCHAR) AS USER_SUBSCRIPTION_TIER,
    CAST(TRIM(CONTENT_ID) AS VARCHAR) AS CONTENT_ID,
    CAST(TRIM(CONTENT_TITLE) AS VARCHAR) AS CONTENT_TITLE,
    CAST(TRIM(CONTENT_GENRE) AS VARCHAR) AS CONTENT_GENRE,
    CAST(TRIM(CONTENT_RELEASE_DATE) AS DATE) AS CONTENT_RELEASE_DATE,
    CAST(CONTENT_DURATION_MINUTES AS NUMBER) AS CONTENT_DURATION_MINUTES,
    CAST(TRIM(WATCH_DATE) AS DATE) AS WATCH_DATE,
    CAST(TRIM(DEVICE_TYPE) AS VARCHAR) AS DEVICE_TYPE,
    CAST(MINUTES_WATCHED AS NUMBER) AS MINUTES_WATCHED,
    CAST(COMPLETED_FLAG AS NUMBER) AS COMPLETED_FLAG,
    CAST(RATING_GIVEN AS FLOAT) AS RATING_GIVEN
FROM
    {{ source('raw_data', 'WATCH_EVENTS_FLAT') }}