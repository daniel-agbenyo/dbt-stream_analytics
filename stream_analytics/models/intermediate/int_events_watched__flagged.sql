WITH BASE AS (
SELECT 
    EVENT_ID,
    USER_ID,
    USER_NAME,
    USER_COUNTRY,
    USER_SUBSCRIPTION_TIER,
    CONTENT_ID,
    CONTENT_TITLE,
    CONTENT_GENRE,
    CONTENT_RELEASE_DATE,
    CONTENT_DURATION_MINUTES,
    MINUTES_WATCHED,
    DEVICE_TYPE,
    RATING_GIVEN,
    COMPLETED_FLAG,
    WATCH_DATE,
    CONTENT_DURATION_MINUTES - MINUTES_WATCHED as DIFF_MINUTES
from 
    {{ ref('stg_watch_events_flat__watch_events') }}
),
FLAGGED AS (
SELECT 
    * EXCLUDE (COMPLETED_FLAG),
    CASE
        WHEN DIFF_MINUTES <= 10 and COMPLETED_FLAG = 0 then 1
        when DIFF_MINUTES > 10 and COMPLETED_FLAG = 1 then 0
        else COMPLETED_FLAG
        end as COMPLETED_FLAG
FROM BASE
)
SELECT 
    *
FROM FLAGGED
